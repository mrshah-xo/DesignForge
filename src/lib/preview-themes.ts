import type { ColorRole, ColorToken, DesignTokens } from '@/lib/types'
import { FALLBACK_HEX, isHex, readableOn } from '@/components/preview/live-preview'

/**
 * Preview theme variants.
 *
 * The live preview always renders from a DesignTokens object, so a "theme"
 * is simply a derived copy of the tokens with a different color atmosphere.
 * Non-color fields (brand, typography, radius, shadows, copy) are inherited
 * unchanged, so switching themes never changes the brand's structure.
 */

export type PreviewThemeId = 'recommended' | 'light' | 'dark' | 'ai'

export interface PreviewThemeOption {
  id: PreviewThemeId
  label: string
  description: string
}

export const PREVIEW_THEMES: PreviewThemeOption[] = [
  {
    id: 'recommended',
    label: 'Recommended',
    description: 'Best outcome — generated by AI from your research',
  },
  {
    id: 'light',
    label: 'Light',
    description: 'Bright surfaces with the same brand colors',
  },
  {
    id: 'dark',
    label: 'Dark',
    description: 'Dark surfaces with the same brand colors',
  },
  {
    id: 'ai',
    label: 'AI from research',
    description: 'A new theme direction proposed by AI from the research findings',
  },
]

// ---------- Color math (client-safe, no dependencies) ----------

function hexToRgb(hex: string): { r: number; g: number; b: number } | null {
  const full = /^#[0-9A-Fa-f]{6}$/.test(hex)
    ? hex
    : /^#([0-9A-Fa-f]{3})$/.test(hex)
      ? `#${hex.slice(1).split('').map((c) => c + c).join('')}`
      : null
  if (!full) return null
  const n = parseInt(full.slice(1), 16)
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 }
}

function rgbToHex(r: number, g: number, b: number): string {
  const to = (v: number) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')
  return `#${to(r)}${to(g)}${to(b)}`
}

/** hex -> { h (0-360), s (0-1), l (0-1) } */
function hexToHsl(hex: string): { h: number; s: number; l: number } {
  const rgb = hexToRgb(hex)
  if (!rgb) return { h: 0, s: 0, l: 0.5 }
  const { r, g, b } = rgb
  const rn = r / 255
  const gn = g / 255
  const bn = b / 255
  const max = Math.max(rn, gn, bn)
  const min = Math.min(rn, gn, bn)
  const l = (max + min) / 2
  if (max === min) return { h: 0, s: 0, l }
  const d = max - min
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  let h: number
  if (max === rn) h = ((gn - bn) / d + (gn < bn ? 6 : 0)) / 6
  else if (max === gn) h = ((bn - rn) / d + 2) / 6
  else h = ((rn - gn) / d + 4) / 6
  return { h: h * 360, s, l }
}

/** { h, s, l } -> hex. Lightness is accepted in either 0-1 or 0-100 scale. */
function hslToHex(h: number, s: number, l: number): string {
  const hn = ((h % 360) + 360) % 360 / 360
  const sn = Math.max(0, Math.min(1, s))
  // Normalize lightness: call sites pass 0-100 values (e.g. 8, 95, 98.5);
  // clamping those to [0, 1] silently forced every color to white.
  const ln = Math.max(0, Math.min(1, l > 1 ? l / 100 : l))
  if (sn === 0) {
    const v = Math.round(ln * 255)
    return rgbToHex(v, v, v)
  }
  const q = ln < 0.5 ? ln * (1 + sn) : ln + sn - ln * sn
  const p = 2 * ln - q
  const channel = (t: number): number => {
    let tn = t
    if (tn < 0) tn += 1
    if (tn > 1) tn -= 1
    if (tn < 1 / 6) return p + (q - p) * 6 * tn
    if (tn < 1 / 2) return q
    if (tn < 2 / 3) return p + (q - p) * (2 / 3 - tn) * 6
    return p
  }
  return rgbToHex(channel(hn + 1 / 3) * 255, channel(hn) * 255, channel(hn - 1 / 3) * 255)
}

const roleHex = (tokens: DesignTokens, role: ColorRole): string => {
  const hex = tokens.colors?.[role]?.hex
  return isHex(hex) ? hex : FALLBACK_HEX[role]
}

const token = (hex: string, name: string, usage: string): ColorToken => ({ hex, name, usage })

// ---------- Variant builders ----------

/** Bright-surface variant: same brand hue, light neutral surfaces tinted by it. */
export function deriveLightVariant(base: DesignTokens): DesignTokens {
  const primary = roleHex(base, 'primary')
  const { h } = hexToHsl(primary)
  const sat = Math.min(hexToHsl(primary).s, 0.5)
  const accentHue = hexToHsl(roleHex(base, 'accent')).h
  const colors: Record<ColorRole, ColorToken> = {
    primary: token(primary, base.colors?.primary?.name ?? 'Primary', base.colors?.primary?.usage ?? 'Primary actions and highlights'),
    primaryForeground: token(readableOn(primary), 'On primary', 'Text and icons on primary'),
    secondary: token(hslToHex(h, sat * 0.4, 94), 'Secondary surface', 'Soft secondary fills and chips'),
    accent: token(hslToHex(accentHue, Math.min(sat + 0.15, 0.7), 93), 'Accent tint', 'Badges, chips and soft highlights'),
    background: token(hslToHex(h, sat * 0.24, 98.5), 'Light canvas', 'Page and section backgrounds'),
    foreground: token(hslToHex(h, 0.16, 10), 'Ink text', 'Primary text on light surfaces'),
    muted: token(hslToHex(h, sat * 0.3, 95.5), 'Tinted surface', 'Cards, wells and secondary fills'),
    mutedForeground: token(hslToHex(h, 0.09, 42), 'Soft text', 'Secondary text and captions'),
    border: token(hslToHex(h, sat * 0.3, 88), 'Hairline', 'Dividers, outlines and input borders'),
    success: token(roleHex(base, 'success'), base.colors?.success?.name ?? 'Success', 'Positive states'),
    warning: token(roleHex(base, 'warning'), base.colors?.warning?.name ?? 'Warning', 'Caution states'),
    danger: token(roleHex(base, 'danger'), base.colors?.danger?.name ?? 'Danger', 'Destructive and error states'),
  }
  return { ...base, colors }
}

/** Dark-surface variant: same brand hue, deep graphite surfaces tinted by it. */
export function deriveDarkVariant(base: DesignTokens): DesignTokens {
  const primaryRaw = roleHex(base, 'primary')
  const { h, s } = hexToHsl(primaryRaw)
  // Brighten the primary if it would sink into the dark background.
  const primary = hexToHsl(primaryRaw).l < 0.45 ? hslToHex(h, Math.min(s, 0.7), 0.62) : primaryRaw
  const accentHue = hexToHsl(roleHex(base, 'accent')).h
  const accentSat = Math.min(hexToHsl(roleHex(base, 'accent')).s, 0.55)
  const colors: Record<ColorRole, ColorToken> = {
    primary: token(primary, base.colors?.primary?.name ?? 'Primary', 'Primary actions and highlights'),
    primaryForeground: token(readableOn(primary), 'On primary', 'Text and icons on primary'),
    secondary: token(hslToHex(h, Math.min(s, 0.2) * 0.5, 16), 'Elevated surface', 'Secondary fills on dark'),
    accent: token(hslToHex(accentHue, accentSat, 24), 'Accent on dark', 'Badges, chips and soft highlights'),
    background: token(hslToHex(h, Math.min(s, 0.3) * 0.6, 8), 'Night canvas', 'Page and section backgrounds'),
    foreground: token(hslToHex(h, 0.12, 95), 'Snow text', 'Primary text on dark surfaces'),
    muted: token(hslToHex(h, Math.min(s, 0.25) * 0.5, 14), 'Deep surface', 'Cards, wells and secondary fills'),
    mutedForeground: token(hslToHex(h, 0.08, 64), 'Muted text on dark', 'Secondary text and captions'),
    border: token(hslToHex(h, Math.min(s, 0.25) * 0.5, 21), 'Dark hairline', 'Dividers, outlines and input borders'),
    success: token(roleHex(base, 'success'), base.colors?.success?.name ?? 'Success', 'Positive states'),
    warning: token(roleHex(base, 'warning'), base.colors?.warning?.name ?? 'Warning', 'Caution states'),
    danger: token(roleHex(base, 'danger'), base.colors?.danger?.name ?? 'Danger', 'Destructive and error states'),
  }
  return { ...base, colors }
}

/** Resolve the tokens for a given preview theme id. */
export function themeTokens(
  base: DesignTokens,
  themeId: PreviewThemeId,
  aiTheme: DesignTokens | null,
): DesignTokens {
  switch (themeId) {
    case 'light':
      return deriveLightVariant(base)
    case 'dark':
      return deriveDarkVariant(base)
    case 'ai':
      return aiTheme ?? base
    default:
      return base
  }
}

/** Small swatch pair (background + primary) used on the theme pills. */
export function themeSwatches(
  base: DesignTokens,
  themeId: PreviewThemeId,
  aiTheme: DesignTokens | null,
): { bg: string; fg: string } {
  const t = themeTokens(base, themeId, aiTheme)
  return { bg: roleHex(t, 'background'), fg: roleHex(t, 'primary') }
}
